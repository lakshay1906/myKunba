export function getT(locale: Locale) {
  const t = translations[locale] ?? translations.en
  return (key: string) => t[key] ?? translations.en[key] ?? key
}

/** Server-only: parse locale from request (e.g. x-locale header). */
export function parseLocaleFromHeader(headerValue: string | null): Locale {
  const raw = headerValue ?? 'en'
  return locales.includes(raw as Locale) ? (raw as Locale) : 'en'
}
